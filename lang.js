let lang = "th";
try { lang = localStorage.getItem("site-lang") || "th"; } catch (e) { /* the saved choice is only a convenience */ }

// English text in, the current language out. {name} is filled from vars.
function t(text, vars = {}) {
  let out = lang === "th" ? (THAI[text] ?? text) : text;
  for (const key in vars) out = out.replace("{" + key + "}", vars[key]);
  return out;
}

// Picks the current language from a { th, en } value in site-data.js.
function tx(value) {
  return value[lang];
}

function setLang(next) {
  lang = next;
  try { localStorage.setItem("site-lang", next); } catch (e) { /* see above */ }
}

// Translates the fixed text in index.html.
function translateStatic() {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-t]").forEach(node => {
    if (!node.dataset.t) node.dataset.t = node.textContent.trim();
    node.textContent = t(node.dataset.t);
  });
}
